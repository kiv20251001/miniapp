import { copyFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import * as esbuild from 'esbuild'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const remindConfig = path.join(root, 'src/domain/remind.config.json')

/** 模板配置不打进包里，运行时读云函数目录旁的同一份 json。 */
function externalRemindConfig() {
  return {
    name: 'external-remind-config',
    setup(build) {
      build.onResolve({ filter: /remind\.config\.json$/ }, () => ({
        path: './remind.config.json',
        external: true,
      }))
    },
  }
}

const shared = {
  bundle: true,
  platform: 'node',
  target: 'node16',
  format: 'cjs',
  external: ['wx-server-sdk'],
  plugins: [externalRemindConfig()],
  alias: {
    '@server-domain': path.resolve(root, '../../server/src/domain'),
  },
}

await esbuild.build({
  ...shared,
  entryPoints: [path.join(root, 'cloudfunctions/api/src/index.ts')],
  outfile: path.join(root, 'cloudfunctions/api/index.js'),
  banner: {
    js: '/* Generated by npm run build:cloud. Edit cloudfunctions/api/src and rebuild. */',
  },
})

await esbuild.build({
  ...shared,
  entryPoints: [path.join(root, 'cloudfunctions/remind/src/index.ts')],
  outfile: path.join(root, 'cloudfunctions/remind/index.js'),
  banner: {
    js: '/* Generated by npm run build:cloud. Edit cloudfunctions/remind/src and rebuild. */',
  },
})

for (const name of ['api', 'remind']) {
  copyFileSync(remindConfig, path.join(root, 'cloudfunctions', name, 'remind.config.json'))
}

console.log('cloud functions bundled to cloudfunctions/api and cloudfunctions/remind')
